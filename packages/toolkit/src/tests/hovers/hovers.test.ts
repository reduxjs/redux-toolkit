import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'

const testDir = path.dirname(fileURLToPath(import.meta.url))
const packageRoot = path.resolve(testDir, '../../..')
const fixturePath = path
  .join(testDir, 'hoverFixture.ts')
  .replaceAll(path.sep, '/')

// `maximumLength` is missing from the signature in older TS versions that
// type-check this file. Tests only run with the repo's own TS version.
type GetQuickInfo = (
  fileName: string,
  position: number,
  maximumLength?: number,
) => ts.QuickInfo | undefined

const noTruncation = 1_000_000

function createLanguageService() {
  const configPath = path.join(packageRoot, 'tsconfig.test.json')
  const { config } = ts.readConfigFile(configPath, ts.sys.readFile)
  const { options } = ts.parseJsonConfigFileContent(config, ts.sys, packageRoot)

  const host: ts.LanguageServiceHost = {
    getScriptFileNames: () => [fixturePath],
    getScriptVersion: () => '0',
    getScriptSnapshot: (fileName) =>
      fs.existsSync(fileName)
        ? ts.ScriptSnapshot.fromString(fs.readFileSync(fileName, 'utf8'))
        : undefined,
    getCurrentDirectory: () => packageRoot,
    getCompilationSettings: () => options,
    getDefaultLibFileName: (o) => ts.getDefaultLibFilePath(o),
    fileExists: ts.sys.fileExists,
    readFile: ts.sys.readFile,
    readDirectory: ts.sys.readDirectory,
    directoryExists: ts.sys.directoryExists,
    getDirectories: ts.sys.getDirectories,
    realpath: ts.sys.realpath,
  }

  return ts.createLanguageService(host, ts.createDocumentRegistry())
}

describe('editor hover text', () => {
  const service = createLanguageService()

  test('fixture has no type errors', () => {
    const messages = service
      .getSemanticDiagnostics(fixturePath)
      .map((d) => ts.flattenDiagnosticMessageText(d.messageText, '\n'))

    expect(messages).toEqual([])
  }, 60_000)

  test('hover text matches snapshot', async () => {
    const getQuickInfo = service.getQuickInfoAtPosition.bind(
      service,
    ) as GetQuickInfo
    const text = fs.readFileSync(fixturePath, 'utf8')
    const sections = ['# Editor hover snapshots', '']

    sections.push(
      'Generated by `hovers.test.ts` from `hoverFixture.ts`.',
      'Each entry is the untruncated hover text. Editors cut hovers off at 500 characters.',
      'Run `pnpm test hovers -u` to update after an intended change.',
      '',
    )

    for (const match of text.matchAll(/\/\*\?(\w+)\*\/\s*/g)) {
      const position = match.index + match[0].length
      const quickInfo = getQuickInfo(fixturePath, position, noTruncation)
      if (!quickInfo) {
        throw new Error(`No hover text for marker "${match[1]}"`)
      }
      const hover = ts.displayPartsToString(quickInfo.displayParts)

      sections.push(
        `## ${match[1]} (${hover.length} chars)`,
        '',
        '```ts',
        hover,
        '```',
        '',
      )
    }

    await expect(sections.join('\n')).toMatchFileSnapshot(
      './__snapshots__/hovers.md',
    )
  }, 60_000)
})
